"""Parity with Hermes core's ``tools.url_safety.is_safe_url``.

The maintainer's review asked for HTTP checks to "refuse private, loopback, link-local and
metadata hosts (the behaviour of core's ``tools.url_safety.is_safe_url``)". Parity with core is
therefore a requirement, not a nicety.

Two layers:

* ``EXPECTED`` is a frozen table of the verdict core returns for each URL. It is checked always,
  including on a bare plugin checkout with no Hermes present. It was generated by running
  ``scripts/core_parity.py`` against a real Hermes checkout at commit ``ff6781e8e1``; 35/35 cases
  agree.
* When core *is* importable (run inside a Hermes checkout), the table is regenerated live and
  compared, so a core change that widens or narrows the policy is caught.
"""
import pytest

from ledger.url_safety import check_url

# url -> verdict returned by core's is_safe_url. Frozen so the suite runs without Hermes.
EXPECTED = {
    # allowed
    "https://example.com/": True,
    "http://example.com/x": True,
    # loopback
    "http://127.0.0.1/": False,
    "http://127.1.2.3/": False,
    "http://[::1]/": False,
    "http://localhost/": False,
    "http://0.0.0.0/": False,
    # private
    "http://10.0.0.1/": False,
    "http://192.168.1.1/": False,
    "http://172.16.5.5/": False,
    "http://[fc00::1]/": False,
    # link-local and CGNAT
    "http://169.254.1.1/": False,
    "http://[fe80::1]/": False,
    "http://100.64.0.1/": False,
    # cloud metadata, including the IPv4-mapped form
    "http://169.254.169.254/latest/meta-data/": False,
    "http://169.254.170.2/": False,
    "http://169.254.169.253/": False,
    "http://100.100.100.200/": False,
    "http://[fd00:ec2::254]/": False,
    "http://[::ffff:169.254.169.254]/": False,
    "http://metadata.google.internal/": False,
    "http://metadata.goog/": False,
    # schemes
    "file:///tmp/example.txt": False,
    "ftp://example.com/": False,
    "gopher://x/": False,
    "data:text/plain,x": False,
    "ws://example.com/": False,
    # ambiguous authorities
    "https://user:pass@example.com/": False,
    "http://example.com\\@127.0.0.1/": False,
    "http://example.com:99999/": False,
    "http://example.com%2f@127.0.0.1/": False,
    "http://127.0.0.1\u3002evil.com/": False,
    # malformed
    "https://": False,
    "not-a-url": False,
    "": False,
}


@pytest.mark.parametrize("url", sorted(EXPECTED))
def test_matches_core_verdict(url):
    ours, _reason = check_url(url)
    assert ours == EXPECTED[url], f"plugin={ours} core={EXPECTED[url]} for {url!r}"


def test_plugin_is_never_more_permissive_than_core():
    """A plugin stricter than core is acceptable; looser is a security regression."""
    looser = [u for u, allowed in EXPECTED.items() if check_url(u)[0] and not allowed]
    assert looser == [], f"plugin allowed URLs core blocks: {looser}"


def test_metadata_stays_blocked_when_private_urls_allowed():
    """``allow_private_urls`` must not re-enable the cloud-metadata floor."""
    for url in (
        "http://169.254.169.254/",
        "http://100.100.100.200/",
        "http://metadata.google.internal/",
    ):
        allowed, reason = check_url(url, allow_private=True)
        assert not allowed, f"{url} allowed with allow_private=True"
        assert "metadata" in reason


def test_private_allowed_only_with_the_opt_in():
    url = "http://127.0.0.1:8080/health"
    assert check_url(url)[0] is False
    assert check_url(url, allow_private=True)[0] is True


def test_live_core_agreement_when_available():
    """When a Hermes checkout is importable, compare against it directly."""
    core = pytest.importorskip("tools.url_safety", reason="Hermes core not importable")
    disagreements = [
        (u, core.is_safe_url(u), check_url(u)[0])
        for u in EXPECTED
        if core.is_safe_url(u) != check_url(u)[0]
    ]
    assert disagreements == [], f"plugin and live core disagree: {disagreements}"
